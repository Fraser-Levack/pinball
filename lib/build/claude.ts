// Runs Claude Code headless to build whatever a finished prompt asks for, in a new folder on this
// computer. Server-only (used by the routes in app/api/build).
//
// Claude runs locked down, because the prompts are random and nobody is there to approve steps:
//   --restricted         no Bash/PowerShell or other code-running tools, file tools confined to the
//                        build folder, user/project settings files ignored
//   --tools              only file tools are available at all
//   --permission-prompts anything that would need approval is refused instead of waiting forever
//   --strict-mcp-config  none of your MCP servers are loaded

import { type ChildProcess, spawn } from "node:child_process";
import { statSync } from "node:fs";
import { mkdir, readdir, stat, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";

/** Where builds go: one folder per build. Override with PINBALL_BUILD_DIR. */
export const BUILD_ROOT = path.resolve(process.env.PINBALL_BUILD_DIR || path.join(os.homedir(), "pinball-builds"));
const TIME_LIMIT_MS = 15 * 60 * 1000;
const PROMPT_FILE = "pinball-prompt.txt"; // the prompt is saved here after the build, for reference

const SYSTEM_PROMPT = [
  "You are building a small project from a prompt that a player generated by playing a pinball game.",
  "The prompt is random and may be silly or vague: make a fun, sensible interpretation of it.",
  "Build it as a static web page that works by opening index.html straight from disk in a browser:",
  "an index.html in the current directory, with any CSS/JS inline or in files next to it.",
  "No build step, no npm packages, no server.",
  "Keep it small enough to finish in a few minutes.",
  "If the prompt asks for anything harmful, unsafe or impossible, build a harmless, playful take on it instead.",
  "When you're done, reply with one or two plain sentences saying what you made.",
].join(" ");

interface ClaudeCommand {
  cmd: string;
  args: string[]; // go before our own arguments
}

const isFile = (p: string) => {
  try {
    return statSync(p).isFile();
  } catch {
    return false;
  }
};

/**
 * Where Claude Code is installed. The dev server's PATH can be out of date (e.g. a terminal or
 * editor opened before Claude Code was installed), so after PATH this checks the usual install
 * locations too. Set CLAUDE_BIN to a full path to override.
 */
function findClaude(): ClaudeCommand | null {
  const override = process.env.CLAUDE_BIN;
  if (override) return isFile(override) ? { cmd: override, args: [] } : null;

  const win = process.platform === "win32";
  const home = os.homedir();
  const name = win ? "claude.exe" : "claude";
  const dirs = [
    ...(process.env.PATH ?? "").split(path.delimiter).filter(Boolean),
    path.join(home, ".local", "bin"), // native installer
    path.join(home, ".claude", "local"), // older local installs
    ...(win ? [] : ["/opt/homebrew/bin", "/usr/local/bin", "/usr/bin"]),
  ];
  for (const dir of dirs) {
    const p = path.join(dir, name);
    if (isFile(p)) return { cmd: p, args: [] };
  }

  // npm global install: its `claude` is a shell/.cmd wrapper, so run the CLI with Node directly.
  const npmRoots = win
    ? [path.join(process.env.APPDATA || path.join(home, "AppData", "Roaming"), "npm", "node_modules")]
    : ["/usr/local/lib/node_modules", "/opt/homebrew/lib/node_modules", path.join(home, ".npm-global", "lib", "node_modules")];
  for (const root of npmRoots) {
    const cli = path.join(root, "@anthropic-ai", "claude-code", "cli.js");
    if (isFile(cli)) return { cmd: process.execPath, args: [cli] };
  }
  return null;
}

export type BuildEvent =
  | { type: "start"; id: string; dir: string }
  | { type: "status"; text: string }
  | { type: "file"; action: "created" | "edited"; path: string }
  | { type: "done"; id: string; dir: string; summary: string; files: string[] }
  | { type: "error"; message: string };

const ID_RE = /^[A-Za-z0-9_-]{1,120}$/;

/** The folder for a build id, or null if the id isn't one we'd have made. */
export function buildDir(id: string): string | null {
  return ID_RE.test(id) ? path.join(BUILD_ROOT, id) : null;
}

function newBuildId(prompt: string): string {
  const d = new Date();
  const pad = (n: number) => String(n).padStart(2, "0");
  const stamp = `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}_${pad(d.getHours())}-${pad(d.getMinutes())}-${pad(d.getSeconds())}`;
  const slug = prompt
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .split("-")
    .filter(Boolean)
    .slice(0, 6)
    .join("-")
    .slice(0, 40)
    .replace(/-+$/, "");
  return slug ? `${stamp}_${slug}` : stamp;
}

/** Make a fresh, empty folder for this build (never reuse one). */
async function makeBuildFolder(prompt: string): Promise<{ id: string; dir: string }> {
  await mkdir(BUILD_ROOT, { recursive: true });
  const base = newBuildId(prompt);
  for (let n = 1; ; n++) {
    const id = n === 1 ? base : `${base}-${n}`;
    const dir = path.join(BUILD_ROOT, id);
    try {
      await mkdir(dir);
      return { id, dir };
    } catch (e) {
      if ((e as NodeJS.ErrnoException).code !== "EEXIST" || n > 50) throw e;
    }
  }
}

async function listFiles(dir: string): Promise<string[]> {
  const entries = await readdir(dir, { recursive: true, withFileTypes: true });
  return entries
    .filter((e) => e.isFile())
    .map((e) => path.relative(dir, path.join(e.parentPath, e.name)).split(path.sep).join("/"))
    .filter((f) => f !== PROMPT_FILE)
    .sort()
    .slice(0, 200);
}

const oneLine = (s: string, max = 220) => {
  const t = s.replace(/\s+/g, " ").trim();
  return t.length > max ? `${t.slice(0, max - 1)}…` : t;
};

// Only one build at a time. Kept on globalThis so it survives dev-server hot reloads of this module.
const shared = globalThis as typeof globalThis & { __pinballBuild?: ChildProcess | "starting" | null };

export const isBuilding = () => shared.__pinballBuild != null;

export class BusyError extends Error {
  constructor() {
    super("A build is already running. Wait for it to finish or cancel it first.");
  }
}

/**
 * Start building `prompt`. Claims the one-build lock synchronously (throws BusyError if taken),
 * then reports progress through `emit`, ending with exactly one "done" or "error" event.
 * Returns a function that cancels the build.
 */
export function startBuild(prompt: string, emit: (e: BuildEvent) => void): () => void {
  if (isBuilding()) throw new BusyError();
  shared.__pinballBuild = "starting";

  let child: ChildProcess | null = null;
  let finished = false;
  let stopReason: string | null = null; // set when we kill it ourselves
  let timer: ReturnType<typeof setTimeout> | undefined;

  const finish = (e: BuildEvent) => {
    if (finished) return;
    finished = true;
    clearTimeout(timer);
    shared.__pinballBuild = null;
    emit(e);
  };

  const stop = (reason: string) => {
    if (finished) return;
    stopReason = reason;
    if (child) child.kill();
    else finish({ type: "error", message: reason });
  };

  (async () => {
    // Looked up per build, so installing Claude Code doesn't need a server restart.
    const claude = findClaude();
    if (!claude) {
      finish({
        type: "error",
        message: process.env.CLAUDE_BIN
          ? `CLAUDE_BIN is set to "${process.env.CLAUDE_BIN}", but there's no file there.`
          : `Couldn't find Claude Code on this computer (looked on PATH and in ${path.join(os.homedir(), ".local", "bin")}). ` +
            "Install it, or set CLAUDE_BIN to the full path of the claude program and restart `npm run dev`.",
      });
      return;
    }

    let id: string;
    let dir: string;
    try {
      ({ id, dir } = await makeBuildFolder(prompt));
    } catch (e) {
      finish({ type: "error", message: `Couldn't create a build folder in ${BUILD_ROOT}: ${(e as Error).message}` });
      return;
    }
    if (stopReason) return finish({ type: "error", message: stopReason });
    emit({ type: "start", id, dir });

    const args = [
      ...claude.args,
      "-p",
      "--output-format", "stream-json",
      "--verbose",
      "--restricted",
      "--strict-mcp-config",
      "--tools", "Read,Write,Edit,Glob,Grep",
      "--permission-mode", "acceptEdits",
      "--permission-prompts", "none",
      "--no-session-persistence",
      "--disable-slash-commands",
      "--append-system-prompt", SYSTEM_PROMPT,
    ];
    // Claude Code won't start if it thinks it's nested inside another Claude Code session
    // (e.g. when `npm run dev` was launched from one); this build is deliberately separate.
    const env = { ...process.env };
    delete env.CLAUDECODE;

    // The prompt goes in on stdin, so it never passes through a shell or command-line quoting.
    child = spawn(claude.cmd, args, { cwd: dir, env, stdio: ["pipe", "pipe", "pipe"], windowsHide: true });
    shared.__pinballBuild = child;
    timer = setTimeout(() => stop(`Build stopped: it ran for more than ${TIME_LIMIT_MS / 60000} minutes.`), TIME_LIMIT_MS);

    let result: { ok: boolean; text: string } | null = null;
    let stderr = "";
    let buf = "";

    const handleLine = (line: string) => {
      let m: any;
      try {
        m = JSON.parse(line);
      } catch {
        return;
      }
      if (m.type === "assistant" && Array.isArray(m.message?.content)) {
        for (const c of m.message.content) {
          if (c.type === "text" && typeof c.text === "string" && c.text.trim()) {
            emit({ type: "status", text: oneLine(c.text) });
          } else if (c.type === "tool_use" && (c.name === "Write" || c.name === "Edit")) {
            const file = typeof c.input?.file_path === "string" ? c.input.file_path : "";
            const rel = path.relative(dir, path.resolve(dir, file));
            const shown = rel.startsWith("..") || path.isAbsolute(rel) ? path.basename(file) : rel;
            emit({ type: "file", action: c.name === "Write" ? "created" : "edited", path: shown.split(path.sep).join("/") });
          }
        }
      } else if (m.type === "system" && m.subtype === "permission_denied") {
        emit({ type: "status", text: "Claude tried something outside its sandbox and was stopped." });
      } else if (m.type === "result") {
        const ok = m.subtype === "success" && !m.is_error;
        result = { ok, text: typeof m.result === "string" ? m.result : String(m.subtype ?? "") };
      }
    };

    child.stdout!.setEncoding("utf8");
    child.stdout!.on("data", (chunk: string) => {
      buf += chunk;
      let i;
      while ((i = buf.indexOf("\n")) >= 0) {
        handleLine(buf.slice(0, i).trim());
        buf = buf.slice(i + 1);
      }
    });
    child.stderr!.setEncoding("utf8");
    child.stderr!.on("data", (chunk: string) => {
      stderr = (stderr + chunk).slice(-2000);
    });

    child.on("error", (e: NodeJS.ErrnoException) => {
      finish({ type: "error", message: `Couldn't start Claude Code (${claude.cmd}): ${e.message}` });
    });

    child.on("close", async (code) => {
      if (buf.trim()) handleLine(buf.trim());
      if (stopReason) return finish({ type: "error", message: stopReason });
      const r = result as { ok: boolean; text: string } | null;
      if (r?.ok) {
        let files: string[] = [];
        try {
          files = await listFiles(dir);
          await writeFile(path.join(dir, PROMPT_FILE), prompt + "\n", "utf8");
        } catch {}
        finish({ type: "done", id, dir, summary: oneLine(r.text, 600), files });
      } else {
        const detail = r?.text || oneLine(stderr, 400) || `Claude Code exited with code ${code}.`;
        finish({ type: "error", message: `The build didn't finish: ${detail}` });
      }
    });

    child.stdin!.on("error", () => {}); // if Claude exits before reading the prompt, report that via "close"
    child.stdin!.end(prompt);
  })().catch((e) => finish({ type: "error", message: `Build failed: ${(e as Error).message}` }));

  return () => stop("Build cancelled.");
}

/** Open a finished build: its index.html in the default browser, or else the folder itself. */
export async function openBuild(id: string, target: "page" | "folder"): Promise<boolean> {
  const dir = buildDir(id);
  if (!dir) return false;
  try {
    if (!(await stat(dir)).isDirectory()) return false;
  } catch {
    return false;
  }
  let what = dir;
  if (target === "page") {
    const page = path.join(dir, "index.html");
    try {
      if ((await stat(page)).isFile()) what = page;
    } catch {}
  }
  const [cmd, args] =
    process.platform === "win32"
      ? ["explorer.exe", [what]]
      : process.platform === "darwin"
        ? ["open", [what]]
        : ["xdg-open", [what]];
  const child = spawn(cmd, args, { detached: true, stdio: "ignore", windowsHide: true });
  child.on("error", () => {});
  child.unref();
  return true;
}
