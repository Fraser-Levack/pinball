// Builds a finished prompt with the Claude API, using the player's own Anthropic API key, for when
// the game is hosted (e.g. on Vercel) and there's no Claude Code or disk to build into. Server-only
// (used by app/api/build/cloud and app/api/builds/cloud).
//
// Claude writes the whole page in its reply; nothing is run on the server. The key is used for this
// one request and never stored or logged. Each finished page is signed, so the route that saves it
// to Supabase only accepts pages that really came back from Claude for that prompt.

import { createHmac, randomUUID, timingSafeEqual } from "node:crypto";
import Anthropic from "@anthropic-ai/sdk";
import { addonById } from "../pachinko/addons";
import { MAX_HTML_BYTES, MAX_SUMMARY } from "../builds";
import type { BuildEvent } from "./claude";

const MODEL = "claude-opus-5-5";
/** Stop a little before app/api/build/cloud's maxDuration, so the player gets a proper error. */
export const TIME_LIMIT_MS = 285 * 1000;

const SYSTEM_PROMPT = [
  "You are building a small project from a prompt that a player generated by playing a pinball game.",
  "The prompt is random and may be silly or vague: make a fun, sensible interpretation of it.",
  "Build it as a single, self-contained index.html that works when opened straight from disk:",
  "put all CSS and JS inline, and make any images with inline SVG, canvas or data: URLs.",
  "Give the page a short, catchy <title> of 2 to 5 words naming what it is: it's the app's name in the gallery.",
  "Load nothing from the network (no CDNs, fonts, APIs or external images),",
  "because the page is shared in a sandbox that blocks it. No build step, no npm packages, no server.",
  "Keep it compact (well under 50 KB) so it's written in a couple of minutes.",
  "If the prompt asks for anything harmful, unsafe or impossible, build a harmless, playful take on it instead.",
  "Reply with the complete index.html in one ```html code block, then one or two plain sentences",
  "after the block saying what you made. Write nothing before the code block.",
].join(" ");

/** A finished cloud build, as handed back to the browser and later sent to be saved. */
export interface SignedBuild {
  id: string;
  html: string;
  summary: string;
  signature: string;
}

const API_KEY_RE = /^sk-ant-[A-Za-z0-9_-]{20,250}$/;
export const isApiKey = (k: unknown): k is string => typeof k === "string" && API_KEY_RE.test(k);

function signingKey(): string {
  const key = process.env.BUILD_SIGNING_SECRET || process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (!key) throw new Error("BUILD_SIGNING_SECRET or SUPABASE_SERVICE_ROLE_KEY must be set");
  return key;
}

function sign(id: string, prompt: string, html: string, summary: string): string {
  return createHmac("sha256", signingKey())
    .update(JSON.stringify(["pinball-cloud-build-v1", id, prompt, html, summary]))
    .digest("base64url");
}

/** True if `build` is exactly what a cloud build of `prompt` returned. */
export function verifyBuild(prompt: string, build: Partial<SignedBuild> | null | undefined): build is SignedBuild {
  if (!build) return false;
  const { id, html, summary, signature } = build;
  if (typeof id !== "string" || typeof html !== "string" || typeof summary !== "string" || typeof signature !== "string") {
    return false;
  }
  const expected = Buffer.from(sign(id, prompt, html, summary));
  const given = Buffer.from(signature);
  return expected.length === given.length && timingSafeEqual(expected, given);
}

function addonPrompt(prompt: string, html: string, addons: string[]): string {
  const list = addons.map((id) => `- ${addonById(id)?.instruction ?? id}`).join("\n");
  return [
    "This index.html was built from this prompt:",
    prompt,
    "",
    "```html",
    html,
    "```",
    "",
    "Improve it by adding these add-ons, keeping everything that already works:",
    list,
    "",
    "Reply with the complete updated index.html, keeping to the same rules: one self-contained file, nothing loaded from the network.",
  ].join("\n");
}

const oneLine = (s: string, max = 220) => {
  const t = s.replace(/\s+/g, " ").trim();
  return t.length > max ? `${t.slice(0, max - 1)}…` : t;
};

/** Splits Claude's reply into the page and the sentences about it. */
function parseReply(text: string): { html: string; summary: string } | null {
  const open = /```html[^\n]*\n/i.exec(text);
  if (open) {
    const start = open.index + open[0].length;
    const close = text.lastIndexOf("```");
    if (close > start) {
      return { html: text.slice(start, close).trim(), summary: oneLine(text.slice(close + 3), MAX_SUMMARY) };
    }
  }
  // No code block: take the page itself if it's there.
  const m = /<!doctype html[\s\S]*<\/html>|<html[\s\S]*<\/html>/i.exec(text);
  return m ? { html: m[0], summary: oneLine(text.slice(m.index + m[0].length), MAX_SUMMARY) } : null;
}

function apiErrorMessage(e: unknown): string {
  if (e instanceof Anthropic.AuthenticationError) return "Anthropic didn't accept that API key. Check it and try again.";
  if (e instanceof Anthropic.PermissionDeniedError) return "That API key isn't allowed to use Claude. Check its workspace and permissions.";
  if (e instanceof Anthropic.RateLimitError) return "Your API key hit its rate limit. Wait a minute and try again.";
  if (e instanceof Anthropic.BadRequestError) return `Anthropic refused the request: ${e.message}`;
  if (e instanceof Anthropic.APIConnectionError) return "Couldn't reach the Claude API. Try again in a moment.";
  if (e instanceof Anthropic.APIError) return `The Claude API had a problem (${e.status ?? "no status"}). Try again in a moment.`;
  return `Build failed: ${(e as Error).message}`;
}

/** A second pass that adds pachinko add-ons to an earlier, signed cloud build of the same prompt. */
export interface CloudAddonPass {
  base: SignedBuild;
  addons: string[];
}

/**
 * Build `prompt` with the Claude API, or with `pass`, add add-ons to an earlier build of it. Reports
 * progress through `emit`, ending with exactly one "done" (carrying the signed page) or "error" event.
 * Returns a function that cancels the build.
 */
export function startCloudBuild(apiKey: string, prompt: string, emit: (e: BuildEvent) => void, pass?: CloudAddonPass): () => void {
  const client = new Anthropic({ apiKey });
  const id = pass?.base.id ?? randomUUID();
  let finished = false;
  let stopReason: string | null = null;
  let stream: ReturnType<typeof client.beta.messages.stream> | null = null;

  const finish = (e: BuildEvent) => {
    if (finished) return;
    finished = true;
    clearTimeout(timer);
    emit(e);
  };
  const stop = (reason: string) => {
    if (finished) return;
    stopReason = reason;
    stream?.abort();
    finish({ type: "error", message: reason });
  };
  const timer = setTimeout(() => stop(`Build stopped: it ran for more than ${Math.round(TIME_LIMIT_MS / 60000)} minutes.`), TIME_LIMIT_MS);

  (async () => {
    const s = (stream = client.beta.messages.stream({
      model: MODEL,
      max_tokens: 64000,
      // Summaries of Claude's thinking are shown as live progress, like the local build's log.
      thinking: { type: "adaptive", display: "summarized" },
      output_config: { effort: "medium" },
      // If Claude's safety checks decline a (random) prompt, let the API retry on its recommended fallback model.
      betas: ["server-side-fallback-2026-07-01"],
      fallbacks: "default",
      system: SYSTEM_PROMPT,
      messages: [{ role: "user", content: pass ? addonPrompt(prompt, pass.base.html, pass.addons) : prompt }],
    }));

    emit({ type: "status", text: pass ? "Claude is reading your page…" : "Claude is planning…" });
    let thought = "";
    let written = 0;
    let lastReport = 0;
    for await (const event of s) {
      if (event.type === "content_block_delta" && event.delta.type === "thinking_delta") {
        thought += event.delta.thinking;
        let i;
        while ((i = thought.indexOf("\n\n")) >= 0) {
          const para = oneLine(thought.slice(0, i).replace(/\*\*/g, ""));
          thought = thought.slice(i + 2);
          if (para) emit({ type: "status", text: para });
        }
      } else if (event.type === "content_block_stop" && thought.trim()) {
        emit({ type: "status", text: oneLine(thought.replace(/\*\*/g, "")) });
        thought = "";
      } else if (event.type === "content_block_delta" && event.delta.type === "text_delta") {
        if (written === 0) emit({ type: "file", action: pass ? "edited" : "created", path: "index.html" });
        written += event.delta.text.length;
        if (Date.now() - lastReport > 4000) {
          lastReport = Date.now();
          emit({ type: "status", text: `Writing index.html… ${Math.max(1, Math.round(written / 1024))} KB so far` });
        }
      }
    }
    if (stopReason) return;

    const message = await s.finalMessage();
    if (message.stop_reason === "refusal") {
      return finish({ type: "error", message: "Claude declined to build this prompt. Play another game for a new one!" });
    }
    if (message.stop_reason === "max_tokens") {
      return finish({ type: "error", message: "The page got too long and was cut off. Try building it again." });
    }
    // If a fallback model took over part-way, only its text counts.
    const lastFallback = message.content.map((b) => b.type).lastIndexOf("fallback");
    const text = message.content
      .slice(lastFallback + 1)
      .map((b) => (b.type === "text" ? b.text : ""))
      .join("");
    const reply = parseReply(text);
    if (!reply || !reply.html) return finish({ type: "error", message: "Claude's reply didn't contain a web page. Try again." });
    if (Buffer.byteLength(reply.html, "utf8") > MAX_HTML_BYTES) {
      return finish({ type: "error", message: "The page Claude wrote is over 1 MB, too big to save. Try again." });
    }
    const summary = reply.summary || pass?.base.summary || "Claude built a page from your prompt.";
    finish({
      type: "done",
      id,
      dir: "",
      summary,
      files: ["index.html"],
      html: reply.html,
      signature: sign(id, prompt, reply.html, summary),
    });
  })().catch((e) => {
    if (stopReason) return;
    finish({ type: "error", message: apiErrorMessage(e) });
  });

  return () => stop("Build cancelled.");
}
